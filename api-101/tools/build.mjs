// Writes index.html (scene hosts) and compositions/captions.html from tools/script.mjs.
// Re-run after changing the script: node tools/build.mjs
import { writeFileSync } from "node:fs";
import { timed } from "./script.mjs";

const total = +(timed.at(-1).start + timed.at(-1).duration).toFixed(2);
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

const hosts = timed.map((s, i) => `      <div
        id="${s.id}"
        data-composition-id="${s.id}"
        data-composition-src="compositions/${s.id}.html"
        data-start="${s.start}"
        data-duration="${s.duration}"
        data-track-index="1"
        data-track-kind="graphics"
        data-width="1080"
        data-height="1080"
        style="z-index: ${i + 1}"
      ></div>`).join("\n");

writeFileSync("index.html", `<!doctype html>
<html lang="en" data-resolution="square">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1080, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <link rel="stylesheet" href="assets/kit.css" />
    <script src="assets/kit.js"></script>
    <style>
      @font-face {
        font-family: "Permanent Marker";
        src: url("assets/fonts/PermanentMarker-Regular.ttf") format("truetype");
        font-weight: 400;
      }
      :root {
        --ground: #0f0f11;
        --card: #18181c;
        --line: #2c2c34;
        --ink: #f2f2f5;
        --muted: #9d9dab;
        --orange: #ff8a3d;
        --blue: #4da3ff;
        --green: #3ddc97;
        --mono: "JetBrains Mono", monospace;
        --sans: "Inter", sans-serif;
      }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: 1080px; height: 1080px; overflow: hidden; background: var(--ground); }
      #root { width: 100%; height: 100%; background: var(--ground); }
    </style>
  </head>
  <body>
    <div
      id="root"
      data-composition-id="main"
      data-start="0"
      data-duration="${total}"
      data-width="1080"
      data-height="1080"
    >
${hosts}
      <div
        id="captions"
        data-composition-id="captions"
        data-composition-src="compositions/captions.html"
        data-start="0"
        data-duration="${total}"
        data-track-index="2"
        data-track-kind="captions"
        data-width="1080"
        data-height="1080"
        style="z-index: 20"
      ></div>
    </div>
    <script>
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`);

// Captions: one group per narration line, absolute times.
const groups = [];
timed.forEach((s) => s.lines.forEach((l, j) => {
  groups.push({ id: `cap-${s.id}-${j}`, text: l.text, start: +(s.start + l.start).toFixed(2), end: +(s.start + l.end).toFixed(2) });
}));
const groupHtml = groups.map((g) => `    <p id="${g.id}" class="cap clip" data-start="${g.start}" data-duration="${+(g.end - g.start + 0.01).toFixed(2)}" data-track-index="0">${esc(g.text)}</p>`).join("\n");
const tw = groups.map((g) => `    cap("#${g.id}", ${g.start}, ${g.end});`).join("\n");

writeFileSync("compositions/captions.html", `<template>
  <style>
    #root { position: absolute; inset: 0; pointer-events: none; }
    .cap {
      position: absolute; left: 162px; top: 812px; width: 756px; margin: 0;
      font-family: "Inter", sans-serif; font-weight: 400; font-size: 30px; line-height: 42px;
      color: #c9c9d3; text-align: center; opacity: 0;
    }
  </style>
  <div id="root" data-composition-id="captions" data-width="1080" data-height="1080">
${groupHtml}
  </div>
  <script>
    const tl = gsap.timeline({ paused: true });
    function cap(sel, start, end) {
      tl.fromTo(sel, { opacity: 0 }, { opacity: 1, duration: 0.15, ease: "power2.out", immediateRender: false }, start);
      tl.to(sel, { opacity: 0, duration: 0.12, ease: "power2.in" }, end - 0.12);
    }
${tw}
    window.__timelines["captions"] = tl;
  </script>
</template>
`);
console.log("total", total, "groups", groups.length);

// ---- scene files
import { readFileSync } from "node:fs";
import { scenes as defs } from "./scenes.mjs";
const kitCss = readFileSync("assets/kit.css", "utf8");
const kitJs = readFileSync("assets/kit.js", "utf8");
for (const s of timed) {
  const d = defs[s.id];
  const end = s.duration;
  const file = `<!-- Generated by tools/build.mjs from tools/scenes.mjs. Edit there and re-run. -->
<template>
  <style>
    @font-face {
      font-family: "Permanent Marker";
      src: url("assets/fonts/PermanentMarker-Regular.ttf") format("truetype");
      font-weight: 400;
    }
    #root { position: absolute; inset: 0; background: var(--ground); }
${kitCss}
${d.css}
  </style>
  <div id="root" data-composition-id="${s.id}" data-width="1080" data-height="1080">
    <div class="k-safe" id="${s.id}-safe">
      <h2 class="k-title"><span id="${s.id}-title">${d.title}</span></h2>
      <svg class="k-underline" viewBox="0 0 250 22"><path id="${s.id}-ul" d="M4 14 C60 4 150 6 246 12"/></svg>
      <div class="k-stage" id="${s.id}-stage" data-layout-allow-overlap>
${d.html}
      </div>
    </div>
  </div>
  <script>
${kitJs}
    (function () {
      const K = window.KIT;
      const tl = gsap.timeline({ paused: true });
      K.open(tl, "#${s.id}-safe", 0, ${d.openFrom ?? 0});
      const typed = K.type(tl, "#${s.id}-title", 0.25, { cps: 15, caret: true });
      K.underline(tl, "#${s.id}-ul", Math.min(typed + 0.05, 2.4), 0.45);
${d.js}
${d.noClose ? "" : `      K.close(tl, "#${s.id}-safe", ${+(end - 0.35).toFixed(2)});`}
      // Pad the timeline to the scene's full slot.
      tl.set({}, {}, ${end});
      window.__timelines["${s.id}"] = tl;
    })();
  </script>
</template>
`;
  writeFileSync(`compositions/${s.id}.html`, file);
}
console.log("scenes written:", timed.map((s) => s.id).join(", "));
